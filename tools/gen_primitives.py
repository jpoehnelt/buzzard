#!/usr/bin/env python3
"""Regenerate crates/buzzard-rsrc/src/blocks/heap/primitives.rs.

The table of built-in function names is taken from LVKit
(https://github.com/pragmatest-dev/lvkit, Apache-2.0). This script reads the
JSON files under src/lvkit/data/primitives of a checkout as data and copies
three things per entry: the id, the function name and the `verified` flag.
Nothing else is read out of the entries, and nothing from the checkout is
imported or executed.

Usage (run from the repository root, isolated mode so that no code next to
the script or in the working directory is imported):

    python3 -I tools/gen_primitives.py \\
        --lvkit /path/to/lvkit \\
        --commit "$(git -C /path/to/lvkit rev-parse HEAD)" \\
        --out crates/buzzard-rsrc/src/blocks/heap/primitives.rs

The script stops with an error, and writes nothing, on a duplicate id, a
malformed entry, or a name with a character outside ALLOWED.
"""

import argparse
import json
import os
import re
import sys

REPO = "https://github.com/pragmatest-dev/lvkit"

# Names end up in Rust string literals and, later, in SVG, Markdown, DOT,
# Mermaid and terminal output. Only these characters are accepted; anything
# else (control characters, quotes, backticks, backslashes, angle brackets,
# brackets, pipes, non-ASCII) stops the run so that a person decides.
ALLOWED = re.compile(r"[A-Za-z0-9 &'()+,\-/?.:]+")
MAX_NAME = 80

# Placeholder names in the source that say nothing about the function:
# "Unknown" and names that start with "Unknown ".
PLACEHOLDER = re.compile(r"Unknown( .*)?")

# Value of the `source` field on entries that LVKit imported from a
# third-party export made with LabVIEW 2025 VI Scripting.
SCRIPTING_SOURCE = "vi-scripting-nodes-lv2025"


def fail(message):
    sys.exit(f"gen_primitives: {message}")


def check_name(name, where):
    if not isinstance(name, str) or not name:
        fail(f"{where}: name is missing or not a string")
    if len(name) > MAX_NAME:
        fail(f"{where}: name longer than {MAX_NAME} characters: {name!r}")
    if not ALLOWED.fullmatch(name):
        fail(f"{where}: name has a character outside the allowed set: {name!r}")
    if name != name.strip() or "  " in name:
        fail(f"{where}: name has leading, trailing or doubled spaces: {name!r}")


def unique_keys(pairs):
    """Build a JSON object, refusing a key that appears twice."""
    out = {}
    for key, value in pairs:
        if key in out:
            raise ValueError(f"duplicate key {key!r}")
        out[key] = value
    return out


def load(directory):
    entries = {}
    origin = {}
    skipped = 0
    scripted = 0
    scripted_in_source = 0
    for file_name in sorted(os.listdir(directory)):
        if not file_name.endswith(".json") or file_name.startswith("_"):
            continue
        path = os.path.join(directory, file_name)
        try:
            with open(path, encoding="utf-8") as handle:
                data = json.load(handle, object_pairs_hook=unique_keys)
        except ValueError as error:
            fail(f"{file_name}: {error}")
        primitives = data.get("primitives") if isinstance(data, dict) else None
        if not isinstance(primitives, dict):
            fail(f"{file_name}: no `primitives` object")
        for key, entry in primitives.items():
            where = f"{file_name}: id {key!r}"
            if not re.fullmatch(r"[1-9][0-9]{0,8}", key):
                fail(f"{where}: id is not a plain decimal number")
            ident = int(key)
            if not isinstance(entry, dict):
                fail(f"{where}: entry is not an object")
            if ident in origin:
                fail(f"{where}: duplicate id, already seen in {origin[ident]}")
            origin[ident] = file_name
            name = entry.get("name")
            verified = entry.get("verified")
            if not isinstance(verified, bool):
                fail(f"{where}: `verified` is missing or not a boolean")
            check_name(name, where)
            from_export = entry.get("source") == SCRIPTING_SOURCE
            scripted_in_source += from_export
            if PLACEHOLDER.fullmatch(name):
                skipped += 1
                continue
            scripted += from_export
            entries[ident] = (name, verified)
    if not entries:
        fail("no entries found")
    return entries, skipped, scripted, scripted_in_source


def render(entries, skipped, scripted, scripted_in_source, commit):
    verified = sum(1 for _, flag in entries.values() if flag)
    lines = [
        "//! Names of built-in functions, keyed by the `primResID` of a `prim`",
        "//! object on the block diagram.",
        "//!",
        "//! Generated by `tools/gen_primitives.py`; do not edit by hand.",
        "//!",
        "//! Source: LVKit, `src/lvkit/data/primitives/*.json`",
        f"//! (<{REPO}>, commit",
        f"//! `{commit}`),",
        "//! Apache License 2.0, Copyright 2025-2026 Ryan Friedman. See `NOTICE` and",
        "//! `LICENSE` in this crate and at the repository root.",
        "//!",
        "//! Modified: only the id, the function name and the `verified` flag of each",
        "//! entry were copied, flattened into one table sorted by id. Entries whose",
        f"//! name is a placeholder were left out ({skipped}). Descriptions, documentation",
        "//! links, terminal names and code were not copied.",
        "//!",
        f"//! Provenance: {len(entries)} entries, {verified} marked verified by LVKit. {scripted} of the",
        f"//! entries ({scripted_in_source} of the {len(entries) + skipped} in the source) are tagged by LVKit as coming from",
        "//! a third-party export made with the VI Scripting interface of LabVIEW",
        "//! 2025 and posted, without a licence statement, in LVKit issue #59. The",
        "//! names are facts about the file format, but this table should be",
        "//! replaced if an independently derived one becomes available.",
        "//!",
        "//! Each row is `(id, name, verified)`. `verified` is LVKit's own flag: true",
        "//! where LVKit records that it confirmed which function the id is, false",
        "//! where the name was taken over without independent confirmation.",
        "",
        "#[rustfmt::skip]",
        "pub(super) const PRIMITIVES: &[(u32, &str, bool)] = &[",
    ]
    for ident in sorted(entries):
        name, flag = entries[ident]
        literal = json.dumps(name, ensure_ascii=True)
        lines.append(f"    ({ident}, {literal}, {'true' if flag else 'false'}),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lvkit", required=True, help="path to an LVKit checkout")
    parser.add_argument("--commit", required=True, help="commit of that checkout")
    parser.add_argument("--out", required=True, help="Rust file to write")
    args = parser.parse_args()
    if not re.fullmatch(r"[0-9a-f]{40}", args.commit):
        fail("--commit must be a full 40-character commit id")
    directory = os.path.join(args.lvkit, "src", "lvkit", "data", "primitives")
    entries, skipped, scripted, scripted_in_source = load(directory)
    text = render(entries, skipped, scripted, scripted_in_source, args.commit)
    with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(
        f"wrote {len(entries)} entries to {args.out} "
        f"({skipped} placeholders skipped, {scripted} from the scripting export)",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
